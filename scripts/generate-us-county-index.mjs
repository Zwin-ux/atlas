function parseGazetteerTable(text) {
  const [headerLine, ...lines] = text.trim().split(/\r?\n/u);
  const headers = headerLine.split("\t").map((header) => header.trim());
  return lines
    .filter(Boolean)
    .map((line) => {
      const columns = line.split("\t");
      return Object.fromEntries(headers.map((header, index) => [header, (columns[index] ?? "").trim()]));
    });
}

function countySlug(name, stateCode) {
  const base = name.replace(/\s+County$/u, "").trim();
  return `${slugify(base)}-${stateCode.toLowerCase()}`;
}

function slugify(value) {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/gu, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/gu, "-")
    .replace(/^-+|-+$/gu, "");
}

function stringLiteral(value) {
  return JSON.stringify(value).replace(/[^\x20-\x7e]/gu, (char) => {
    const code = char.codePointAt(0) ?? 0;
    return code <= 0xffff ? `\\u${code.toString(16).padStart(4, "0")}` : `\\u{${code.toString(16)}}`;
  });
}

function formatNumber(value) {
  if (!Number.isFinite(value)) {
    throw new Error("Encountered a non-finite coordinate in the county source.");
  }
  return String(value);
}

function getOptionValue(values, name) {
  const index = values.indexOf(name);
  if (index === -1) return undefined;
  const value = values[index + 1];
  if (!value || value.startsWith("--")) {
    throw new Error(`${name} requires a value.`);
  }
  return value;
}
