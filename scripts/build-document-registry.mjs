#!/usr/bin/env node

import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, extname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  DOCUMENT_POLICY_VERSION,
  canonicalReplacements,
  classifyKnowledgeSource,
  isKnowledgeSource,
  normalizePath,
} from "./lib/atlas-document-policy.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REGISTRY_PATH = resolve(ROOT, "docs/brain/document-registry.jsonl");
const SUMMARY_PATH = resolve(ROOT, "docs/brain/DOCUMENT_REGISTRY.md");
const GENERATED = new Set([
  "docs/brain/document-registry.jsonl",
  "docs/brain/DOCUMENT_REGISTRY.md",
]);

const files = visibleFiles().filter(isKnowledgeSource).sort();
const entries = files.map(buildEntry);

mkdirSync(dirname(REGISTRY_PATH), { recursive: true });
writeFileSync(REGISTRY_PATH, entries.map((entry) => JSON.stringify(entry)).join("\n") + "\n");
writeFileSync(SUMMARY_PATH, buildSummary(entries));

console.log(
  JSON.stringify(
    {
      ok: true,
      gate: "atlas-document-registry-build",
      policyVersion: DOCUMENT_POLICY_VERSION,
      documentCount: entries.length,
      authorityCounts: countBy(entries, "authority"),
      outputs: [relative(REGISTRY_PATH), relative(SUMMARY_PATH)],
    },
    null,
    2,
  ),
);

function visibleFiles() {
  return gitFiles(["ls-files", "-co", "--exclude-standard", "-z"]);
}

function gitFiles(args) {
  const output = execFileSync("git", args, {
    cwd: ROOT,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  return output
    .split("\0")
    .map(normalizePath)
    .filter(Boolean);
}

function buildEntry(path) {
  const absolute = resolve(ROOT, path);
  const policy = classifyKnowledgeSource(path);
  const generated = GENERATED.has(path);
  const preview = generated ? "" : readPreview(absolute);

  return {
    schemaVersion: 1,
    policyVersion: DOCUMENT_POLICY_VERSION,
    path,
    title: inferTitle(path, preview),
    extension: extname(path).toLowerCase() || null,
    generated,
    lane: policy.lane,
    authority: policy.authority,
    readBeforeWork: policy.readBeforeWork,
    reason: policy.reason,
    canonicalReplacements: canonicalReplacements(policy),
    headings: extractHeadings(preview),
    bytes: generated ? null : statSync(absolute).size,
    sha256: generated ? null : sha256(absolute),
  };
}

function readPreview(path) {
  const source = readFileSync(path);
  return source.subarray(0, 128 * 1024).toString("utf8");
}

function sha256(path) {
  return createHash("sha256").update(readFileSync(path)).digest("hex");
}

function inferTitle(path, source) {
  if (path.endsWith(".json")) {
    try {
      const value = JSON.parse(source);
      const jsonTitle = value?.planningPage?.title ?? value?.app_info?.display_name ?? value?.title ?? value?.name;
      if (typeof jsonTitle === "string" && jsonTitle.trim()) return jsonTitle.trim();
    } catch {
      // A truncated or non-object JSON source falls through to its filename.
    }
  }
  const heading = /^#\s+(.+)$/m.exec(source)?.[1]?.trim();
  if (heading) return heading.replace(/\s+\{.*\}$/, "");
  return path.split("/").at(-1);
}

function extractHeadings(source) {
  return [...source.matchAll(/^#{1,3}\s+(.+)$/gm)]
    .slice(0, 12)
    .map((match) => match[1].trim());
}

function buildSummary(items) {
  const authorityCounts = countBy(items, "authority");
  const laneCounts = countBy(items, "lane");
  const firstReads = items.filter((item) => item.readBeforeWork);
  const review = items.filter((item) => item.authority === "review-required");

  return `# Atlas document registry\n\n` +
    `Generated by \`pnpm brain:build\`. Do not edit this file or the JSONL registry by hand.\n\n` +
    `The registry covers **${items.length}** repository-visible knowledge sources. ` +
    `Historical means retained for provenance, not deleted.\n\n` +
    `## Read first\n\n` +
    table(firstReads, ["path", "lane", "reason"]) +
    `\n## Authority counts\n\n` +
    countTable(authorityCounts) +
    `\n## Lane counts\n\n` +
    countTable(laneCounts) +
    `\n## Review required\n\n` +
    (review.length ? table(review, ["path", "lane", "reason"]) : "None.\n") +
    `\n## Query\n\n` +
    `Run \`pnpm brain:query -- "location truth"\` to rank current and historical sources without treating archive material as instructions.\n\n` +
    `The complete one-record-per-source inventory is \`docs/brain/document-registry.jsonl\`.\n`;
}

function countBy(items, field) {
  return Object.fromEntries(
    [...new Set(items.map((item) => item[field]))]
      .sort()
      .map((value) => [value, items.filter((item) => item[field] === value).length]),
  );
}

function countTable(counts) {
  const rows = Object.entries(counts).map(([name, count]) => ({ name, count }));
  return table(rows, ["name", "count"]);
}

function table(rows, fields) {
  const header = `| ${fields.join(" | ")} |\n| ${fields.map(() => "---").join(" | ")} |\n`;
  return header + rows.map((row) => `| ${fields.map((field) => escapeCell(row[field])).join(" | ")} |`).join("\n") + "\n";
}

function escapeCell(value) {
  return String(value ?? "").replaceAll("|", "\\|").replaceAll("\n", " ");
}

function relative(path) {
  return normalizePath(path.slice(ROOT.length + 1));
}
